def build_quick_facts_doc(collection: str, prefix: str):
    """生成该库的 `-000` 速查表文档。"""
    from scripts.demo_kb_content import D

    statement, rows = QUICK_FACTS[collection]
    body = [statement, ""]
    for i, (title, text) in enumerate(rows, start=1):
        body.append(f"{i}. 【{title}】{text}")
    body += [
        "",
        "本表只列最常被问到的几项现行标准，完整制度见本知识库其他文档。",
        "对本表内容有疑问的，以最新发布的制度正文为准；正文与本表不一致时，请联系制度主管部门确认。",
    ]
    return D(f"{prefix}-000", "现行标准速查表（统一口径）", "\n".join(body))
